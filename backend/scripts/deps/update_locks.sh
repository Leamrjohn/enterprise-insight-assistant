#!/usr/bin/env bash
# E2: regenerate the backend lock files.  Runs inside python:3.12-slim (Linux,
# CPython 3.12: the platform every image and CI job installs on); start it with
# scripts/ops/update-locks.ps1 from the repository root.
#
#   update_locks.sh [package ...]   # packages allowed to move, e.g. pillow pypdf
#
# Every other package keeps the version the current locks already tested:
#   ci-linux-py312.lock    runtime + dev extras (CI); pip-compile keeps its pins
#   base-linux-py312.lock  runtime only (api, beat, report-worker, worker)
#   ml-linux-py312.lock    local model stack on top of base (worker, evaluation)
# base and ml take their versions from the CI lock, so CI tests what the images
# run.  Run from backend/.
set -euo pipefail

pip install --quiet --root-user-action=ignore pip-tools==7.6.2 uv==0.9.5 packaging==25.0
torch_index=https://download.pytorch.org/whl/cpu
upgrade=()
for name in "$@"; do upgrade+=(--upgrade-package "$name"); done

echo "== ci lock"
# pip-compile reuses the hashes already in this lock, so only moved packages
# are fetched.  The editable install in CI builds with --no-build-isolation,
# so it needs setuptools.
echo setuptools > /tmp/ci-build.txt
pip-compile --quiet --allow-unsafe --generate-hashes --no-emit-index-url \
  --no-emit-trusted-host --strip-extras --extra=dev "${upgrade[@]}" \
  --output-file=requirements/ci-linux-py312.lock \
  /tmp/ci-build.txt pyproject.toml requirements/base.txt

# CI lock first, then the old ML lock for model-only packages; named packages move.
python scripts/deps/locks.py pins requirements/ml-linux-py312.lock \
  requirements/ci-linux-py312.lock --except "$@" > /tmp/locked.txt

# base and ml: resolve pins without hashes (uv), download only the files this
# platform installs, and hash those.  pip-compile --generate-hashes on a new
# lock downloads every platform's files instead: over an hour for torch.
lock() {  # input, output, header, extra pip args
  local input=$1 output=$2 header=$3
  shift 3
  # uv resolves in seconds; unsafe-best-match lets torch come from the extra
  # index the way pip itself picks it.
  uv pip compile --quiet --no-emit-index-url --no-header \
    --index-strategy unsafe-best-match --constraint=/tmp/locked.txt "$@" \
    --output-file=/tmp/pins.txt "$input"
  rm -rf /tmp/downloads
  pip download --quiet --no-deps --dest /tmp/downloads "$@" -r /tmp/pins.txt
  python scripts/deps/locks.py hash /tmp/pins.txt --downloads /tmp/downloads \
    --header "$header" --output "$output"
}

echo "== base lock"
lock requirements/base.txt requirements/base-linux-py312.lock \
  "E2 runtime dependencies for the backend images (Linux, CPython 3.12).
Generated by scripts/deps/update_locks.sh from requirements/base.txt with the
CI lock versions as constraints; install with --require-hashes."

echo "== ml lock"
lock requirements/ml.txt requirements/ml-linux-py312.lock \
  "E2 local model dependencies (Linux, CPython 3.12), installed after the base or
CI lock. Generated by scripts/deps/update_locks.sh from requirements/ml.txt;
install with --require-hashes --extra-index-url $torch_index." \
  --extra-index-url "$torch_index"
